def merge_block(path: Path, block: str) -> Path:
    """Insert or replace the OpenFusion block in an existing instructions file."""
    new = f"{MARK_START}\n{block.strip()}\n{MARK_END}\n"
    old = read(path) if path.exists() else ""
    old = old.replace("\r\n", "\n")
    if MARK_START in old and MARK_END in old:
        pre, rest = old.split(MARK_START, 1)
        _, post = rest.split(MARK_END, 1)
        text = pre + new.rstrip("\n") + post
    else:
        text = (old.rstrip("\n") + "\n\n" if old.strip() else "") + new
    return write(path, text)


def render(harness: str, cfg: dict[str, Any], out: Path, merge_instructions: bool = False,
           available: list[str] | None = None, env: dict[str, str] | None = None) -> list[Path]:
    """Write one adapter. `available` narrows each tier to the first usable candidate;
    `env` supplies OPENFUSION_MODEL_* overrides. Both default to off, so checked-in output is stable."""
    if harness not in HARNESSES:
        raise ValueError(f"unknown harness {harness!r}; choose from {list(HARNESSES)}")
    h = HARNESSES[harness]
    if h.name not in cfg["providers"]:
        raise ValueError(f"openfusion.yaml has no providers.{h.name} section")
    c = Ctx(cfg, Path(out), h, available=available, env=dict(env or {}))
    paths = h.write_agents(c)
    paths += render_skill(c)
    if h.extra:
        paths += h.extra(c)
    if h.instructions_file:
        target = c.out / h.instructions_file
        if merge_instructions:
            paths.append(merge_block(target, instructions_text(c)))
        else:
            stem = Path(h.instructions_file).stem
            paths.append(write(c.out / f"{stem}.openfusion.md",
                               f"<!-- Paste into {h.instructions_file} (`openfusion install` does this for you). -->\n\n"
                               + instructions_text(c)))
    return paths


def merge_codex_agents(repo: Path) -> str:
    """Put the [agents] limits from config.openfusion.toml into .codex/config.toml (between markers).
    Never touches the user's model settings; refuses to create duplicate TOML tables."""
    snippet = read(repo / ".codex" / "config.openfusion.toml")
    block = snippet[snippet.index(AGENTS_BLOCK_START):snippet.index(AGENTS_BLOCK_END) + len(AGENTS_BLOCK_END)]
    target = repo / ".codex" / "config.toml"
    old = read(target).replace("\r\n", "\n") if target.exists() else ""
    if AGENTS_BLOCK_START in old and AGENTS_BLOCK_END in old:
        pre, rest = old.split(AGENTS_BLOCK_START, 1)
        text = pre + block + rest.split(AGENTS_BLOCK_END, 1)[1]
    elif re.search(r"^\s*\[(agents|features\.multi_agent_v2)\]", old, re.M):
        return ("Merge the [agents] block of .codex/config.openfusion.toml into your .codex/config.toml by hand "
                "(it already has an [agents] table). It caps subagents and makes un-overridden spawns use the fast worker.")
    else:
        text = (old.rstrip("\n") + "\n\n" if old.strip() else "") + block + "\n"
    write(target, text)
    return (".codex/config.toml: added the OpenFusion [agents] block (subagent cap, fast default for spawns). "
            "Codex loads project config only in trusted projects. Optional: copy the orchestrator model lines "
            "from .codex/config.openfusion.toml.")


def render_all(cfg: dict[str, Any], out: Path) -> dict[str, list[Path]]:
    """Regenerate adapters/<harness>/ for every harness (the checked-in reference output)."""
    result = {}
    for name in HARNESSES:
        dest = Path(out) / name
        if dest.exists():
            shutil.rmtree(dest)
        result[name] = render(name, cfg, dest)
    return result


def install(harness: str, cfg: dict[str, Any], repo: Path, merge_instructions: bool = True,
            codex_profiles_home: Path | None = None, available: list[str] | None = None,
            env: dict[str, str] | None = None) -> tuple[list[Path], list[str]]:
    """Render into a real repo, merge the instructions block, and return next steps."""
    repo = Path(repo).expanduser().resolve()
    if not repo.is_dir():
        raise FileNotFoundError(f"target repo folder not found: {repo}")
    h = HARNESSES[harness]
    paths = render(harness, cfg, repo, merge_instructions=merge_instructions, available=available, env=env)
    steps = []
    for t in cfg["escalation_ladder"]:
        m = resolve_model(cfg, harness, t, available=available, env=env or {})
        if m["source"] == "env":
            steps.append(f"{t}: using {m['model']} from ${m['override']}.")
        elif m["source"] == "fallback":
            steps.append(f"{t}: {m['candidates'][0]} isn't available, using fallback {m['model']}.")
        elif m["source"] == "none":
            steps.append(f"{t}: none of {m['candidates']} is available; the worker inherits the main model. "
                         f"Add a model you have to providers.{harness}.{t}.candidates.")
    if harness == "codex":
        if codex_profiles_home:
            codex_profiles_home.mkdir(parents=True, exist_ok=True)
            for p in sorted((repo / ".codex/profiles").glob("*.config.toml")):
                dst = codex_profiles_home / p.name
                if not dst.exists():
                    shutil.copyfile(p, dst)
                    paths.append(dst)
        steps.append(merge_codex_agents(repo))
    if h.instructions_file and not merge_instructions:
        steps.append(f"Paste {Path(h.instructions_file).stem}.openfusion.md into {h.instructions_file}.")
    steps.append(f"Check the model names in openfusion.yaml -> providers.{harness}, then re-run install if you change them.")
    steps.append(f"Try it: {h.route_cmd} \"fix the failing login test\"")
    steps += list(h.notes)
    return paths, steps
