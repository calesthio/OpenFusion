def _gemini_agents(c: Ctx) -> list[Path]:
    paths = []
    for r in roles(c.cfg):
        body = r.body
        if r.reviewer:
            body += "\nYou are read-only: never write, edit or delete files.\n"
        fm = {"name": c.name(r), "description": r.description, "kind": "local",
              "model": c.model(r)["model"] or "inherit"}
        paths.append(write(c.out / ".gemini" / "agents" / f"{c.name(r)}.md", frontmatter(fm, body)))
    return paths


def _opencode_agents(c: Ctx) -> list[Path]:
    paths = []
    for r in roles(c.cfg):
        m = c.model(r)
        fm: dict[str, Any] = {"description": r.description, "mode": "subagent"}
        if m["model"]:  # omitted = subagent uses the primary agent's model
            fm["model"] = m["model"]
        if m.get("effort"):
            fm["reasoningEffort"] = m["effort"]
        if r.reviewer:
            fm["permission"] = {"edit": "deny"}
        # opencode uses the file name as the agent name.
        paths.append(write(c.out / ".opencode" / "agents" / f"{c.name(r)}.md", frontmatter(fm, r.body)))
    return paths


