def _find_core() -> Path:
    """core/ of a repo checkout, else the copy packaged inside the wheel (openfusion/_data/core)."""
    for cand in (PKG.parents[1], DATA / "core"):
        if (cand / "skill" / "SKILL.md").is_file() and (cand / "openfusion.yaml").is_file():
            return cand
    raise FileNotFoundError("OpenFusion core files not found (broken install?)")


