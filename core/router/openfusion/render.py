"""Render harness adapters from the common core.

The core (single source of truth) is:
  core/openfusion.yaml   tiers, routing rules, and per-harness model names
  core/skill/SKILL.md    the orchestrator skill (template)
  core/prompts/          worker / judge / critic prompts, role descriptions, instructions snippet
  core/router/openfusion the router (copied into every rendered skill so it runs with plain Python)

Each harness adapter below only decides WHERE files go and HOW model names are written for
that tool. It never changes what the skill says. Add a harness = add one entry to HARNESSES.
Everything uses pathlib and writes UTF-8 with LF line endings, so output is identical on
Windows, macOS and Linux.
"""
