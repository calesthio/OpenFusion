# --------------------------------------------------------------------------- helpers
def write(path: Path, text: str) -> Path:
    """UTF-8, LF line endings on every OS."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text if text.endswith("\n") else text + "\n")
    return path


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def fill(template: str, values: dict[str, str]) -> str:
    def sub(m: re.Match) -> str:
        key = m.group(1)
        if key not in values:
            raise KeyError(f"template placeholder {{{{{key}}}}} has no value")
        return values[key]
    return re.sub(r"\{\{([a-z_]+)\}\}", sub, template)


_PLAIN = re.compile(r"[A-Za-z_./][A-Za-z0-9_ .,/()\[\]=+@<>-]*")
_RESERVED = {"y", "n", "yes", "no", "on", "off", "true", "false", "null", "~"}


def yaml_scalar(v: Any) -> str:
    """One YAML scalar. Plain when unambiguous, else a JSON string (always valid YAML)."""
    if isinstance(v, bool):
        return "true" if v else "false"
    if v is None:
        return "null"
    if isinstance(v, (int, float)):
        return str(v)
    s = str(v)
    if _PLAIN.fullmatch(s) and not s.endswith(" ") and s.lower() not in _RESERVED:
        return s
    return json.dumps(s, ensure_ascii=False)


def yaml_dump(data: dict[str, Any], indent: int = 0) -> str:
    """Tiny block-style YAML emitter for frontmatter (dicts, lists of scalars, scalars). Stdlib only."""
    pad, lines = " " * indent, []
    for k, v in data.items():
        key = yaml_scalar(k)
        if isinstance(v, dict):
            lines.append(f"{pad}{key}:" + ("" if v else " {}"))
            if v:
                lines.append(yaml_dump(v, indent + 2))
        elif isinstance(v, (list, tuple)):
            if not v:
                lines.append(f"{pad}{key}: []")
            else:
                lines.append(f"{pad}{key}:")
                lines += [f"{pad}- {yaml_scalar(x)}" for x in v]
        else:
            lines.append(f"{pad}{key}: {yaml_scalar(v)}")
    return "\n".join(lines)


def frontmatter(data: dict[str, Any], body: str) -> str:
    return f"---\n{yaml_dump(data)}\n---\n\n{body.strip()}\n"


def write_snapshots() -> list[Path]:
    """Refresh _data/*.json from the YAML sources (needs PyYAML; run from a checkout)."""
    import yaml
    out = []
    for name, src in SNAPSHOTS.items():
        text = read(src)
        out.append(write(DATA / name, json.dumps({"source": src.relative_to(CORE.parent).as_posix(),
                                                 "source_sha256": source_digest(text),
                                                 "data": yaml.safe_load(text)}, indent=1, ensure_ascii=False)))
    return out


def toml_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)  # JSON string escaping is valid TOML basic-string escaping


def is_placeholder(model: str | None) -> bool:
    return not model or str(model).startswith("<")


# --------------------------------------------------------------------------- roles
@dataclass
class Role:
    key: str          # fast | standard | deep | judge-standard | judge-deep | critic
    tier: str         # which tier's model it runs on
    kind: str         # worker | judge | critic
    description: str
    body: str

    @property
    def reviewer(self) -> bool:
        return self.kind != "worker"


def roles(cfg: dict[str, Any]) -> list[Role]:
    desc = load_yaml(PROMPTS / "roles.yaml")
    ladder = cfg["escalation_ladder"]
    out = [Role(t, t, "worker", desc.get(t, f"OpenFusion {t}-tier worker."),
                fill(read(PROMPTS / "worker.md"), {"tier": t})) for t in ladder]
    for t in ladder[1:]:
        k = f"judge-{t}"
        out.append(Role(k, t, "judge", desc.get(k, f"OpenFusion read-only judge on the {t} tier."),
                        fill(read(PROMPTS / "judge.md"), {"tier": t})))
    ct = cfg["patterns"]["critique"].get("critic_tier", ladder[min(1, len(ladder) - 1)])
    out.append(Role("critic", ct, "critic", desc["critic"], read(PROMPTS / "critic.md")))
    return out


# --------------------------------------------------------------------------- harness spec
@dataclass
class Ctx:
    cfg: dict[str, Any]
    out: Path
    h: "Harness"
    available: list[str] | None = None   # models the user can actually use (install --available)
    env: dict[str, str] = field(default_factory=dict)  # OPENFUSION_MODEL_* overrides (install only)

    @property
    def models(self) -> dict[str, dict[str, Any]]:
        return {t: self.tier_model(t) for t in self.cfg["escalation_ladder"]}

    def name(self, role: Role) -> str:
        return self.h.agent_name(role.key)

    def tier_model(self, tier: str) -> dict[str, Any]:
        """Resolved entry: `model` is the chosen candidate, or None = let the harness pick (inherit)."""
        return resolve_model(self.cfg, self.h.name, tier, available=self.available, env=self.env)

    def model(self, role: Role) -> dict[str, Any]:
        return self.tier_model(role.tier)

    def model_list(self, role: Role) -> list[str]:
        """Ordered candidates still usable (for harnesses with native fallback lists)."""
        m = self.model(role)
        if m.get("source") == "env":
            return [m["model"]]
        if m["model"] is None:
            return []
        return m["candidates"][m["candidates"].index(m["model"]):] if self.available is None else [
            c for c in m["candidates"] if c.strip().lower() in {a.strip().lower() for a in self.available}]


@dataclass
class Harness:
    name: str
    title: str
    skill_dir: str                       # where the skill goes, relative to the repo root
    delegate_how: str
    write_agents: Callable[[Ctx], list[Path]]
    instructions_file: str | None = None  # merged (between markers) on install; None = adapter writes its own
    sep: str = "-"
    status: str = "verified"             # verified against official docs (see docs/HARNESSES.md)
    docs: tuple[str, ...] = ()
    notes: tuple[str, ...] = ()
    extra: Callable[[Ctx], list[Path]] | None = None
    spawn_args: bool = False             # delegation passes model/effort per call (worker table shows them)

    def agent_name(self, role_key: str) -> str:
        return "fusion" + self.sep + role_key.replace("-", self.sep)

    @property
    def route_cmd(self) -> str:
        return f"python {self.skill_dir}/scripts/route.py"


# --------------------------------------------------------------------------- per-harness writers
def _claude_agents(c: Ctx) -> list[Path]:
    paths = []
    for r in roles(c.cfg):
        m = c.model(r)
        fm: dict[str, Any] = {"name": c.name(r), "description": r.description}
        if r.reviewer:
            fm["tools"] = "Read, Grep, Glob, Bash"
        fm["model"] = m["model"] or "inherit"
        if m.get("effort"):
            fm["effort"] = m["effort"]
        paths.append(write(c.out / ".claude" / "agents" / f"{c.name(r)}.md", frontmatter(fm, r.body)))
    return paths


def _codex_agents(c: Ctx) -> list[Path]:
    paths = []
    for r in roles(c.cfg):
        m = c.model(r)
        body = r.body
        lines = [f"name = {toml_str(c.name(r))}", f"description = {toml_str(r.description)}"]
        if is_placeholder(m["model"]):
            lines.append("# model: inherits from parent (no candidate in providers.codex is available)")
        else:
            lines.append(f"model = {toml_str(m['model'])}")
        if m.get("effort"):
            lines.append(f"model_reasoning_effort = {toml_str(m['effort'])}")
        lines.append('developer_instructions = """\n' + body.strip().replace('"""', '\\"\\"\\"') + '\n"""')
        paths.append(write(c.out / ".codex" / "agents" / f"{c.name(r)}.toml", "\n".join(lines)))
    return paths


def _codex_extra(c: Ctx) -> list[Path]:
    paths = []
    for t in c.cfg["escalation_ladder"]:
        m = c.models[t]
        body = [f"# Main-thread profile: codex --profile fusion-{t}   (copy to ~/.codex/)"]
        if not is_placeholder(m["model"]):
            body.append(f"model = {toml_str(m['model'])}")
        if m.get("effort"):
            body.append(f"model_reasoning_effort = {toml_str(m['effort'])}")
        paths.append(write(c.out / ".codex/profiles" / f"fusion-{t}.config.toml", "\n".join(body)))
    std = c.models.get("standard") or c.models[c.cfg["escalation_ladder"][0]]
    top = c.models[c.cfg["escalation_ladder"][-1]]
    fast = c.models[c.cfg["escalation_ladder"][0]]
    d = c.cfg.get("delegation") or {}
    main_model = (f"model = {toml_str(top['model'])}            # main thread / orchestrator: plans, routes, reviews"
                  if not is_placeholder(top["model"]) else "# model = \"...\"   # main thread / orchestrator")
    lines = [
        "# Merge into .codex/config.toml (project) or ~/.codex/config.toml (user).",
        "# Docs: https://learn.chatgpt.com/docs/agent-configuration/subagents",
        main_model,
        f"model_reasoning_effort = {toml_str(top.get('effort', 'medium'))}",
        "",
        AGENTS_BLOCK_START,
        "[agents]",
        "enabled = true",
        f"max_concurrent_threads_per_session = {int(d.get('max_subagents', 3))}",
        "# Spawns without an explicit model run on the fast worker instead of inheriting the main model.",
    ]
    if not is_placeholder(fast["model"]):
        lines.append(f"default_subagent_model = {toml_str(fast['model'])}")
    if fast.get("effort"):
        lines.append(f"default_subagent_reasoning_effort = {toml_str(fast['effort'])}")
    lines += ["", "[features.multi_agent_v2]",
              "expose_spawn_agent_model_overrides = true   # default since openai/codex#32749; keep it on",
              AGENTS_BLOCK_END]
    paths.append(write(c.out / ".codex" / "config.openfusion.toml", "\n".join(lines)))
    return paths


AGENTS_BLOCK_START = "# >>> openfusion agents >>>"
